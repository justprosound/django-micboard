OUTPUT_DIR = ROOT / "docs" / "api" / "reference"
SOURCE_URL = "https://github.com/justprosound/django-micboard/blob/main"
GENERATED_MARKER = "<!-- Generated by scripts/generate_api_docs.py. Do not edit by hand. -->"


