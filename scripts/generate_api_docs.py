"""Generate the Python API reference Markdown consumed by the documentation site.

Griffe parses the ``micboard`` package statically, so the documentation build never
imports Django or needs ``DJANGO_SETTINGS_MODULE``. The emitted Markdown is committed
to ``docs/api/reference/`` so that ``just docs`` stays a single-step build; regenerate
it with ``just docs-api`` whenever the documented modules change.
"""

